export type Key = keyof typeof hr;

const dictionaries: Record<Locale, typeof hr> = { hr, en };

export function translate(locale: Locale, key: Key, vars: Record<string, string> = {}) {
	const text = dictionaries[locale]?.[key] ?? en[key] ?? key;
	return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
